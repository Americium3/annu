"""Build experiments/RESULTS.md from the CSVs written by run_golden.py, grid.py and rules_grid.py.

  python -m experiments.report
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from experiments.golden_eval import paired_bootstrap
from experiments.run_golden import EXPERIMENTS, RESULTS, ROOT

ORDER = ["E0_live_ce", "E0_live_rules", "E1_location_ce", "E1_location_rules", "E3_v2index_ce", "E3_v2index_rules",
         "E4_v2_osm_rules", "E5a_minpool3_rules", "E5b_intent_rules", "E5c_urgent_rules", "E6_plausibility_rules",
         "E7_final_ce", "E7_final_rules", "E8a_solid_evidence_rules", "E8b_solid_off_rules", "E8c_solid_evidence_ce",
         "E9_shipped_defaults", "E10_freetext_baseline", "E10_freetext_service"]


def fmt(x, d=3):
    return "" if pd.isna(x) else (f"{x:.{d}f}" if isinstance(x, float) else str(x))


def table(df, cols):
    head = "| " + " | ".join(cols) + " |\n|" + "|".join("---" for _ in cols) + "|\n"
    return head + "".join("| " + " | ".join(fmt(r[c]) for c in cols) + " |\n" for _, r in df.iterrows())


def main():
    s = pd.read_csv(RESULTS / "golden_dev_summary.csv").set_index("experiment")
    pq = pd.read_csv(RESULTS / "golden_dev_per_query.csv")
    rows = [s.loc[e] for e in ORDER if e in s.index] + [s.loc[e] for e in s.index if e not in ORDER]
    main_tbl = pd.DataFrame(rows).reset_index().rename(columns={"index": "experiment"})
    out = ["# Recommender experiments on golden_eval (dev split)\n",
           "Generated by `python -m experiments.report`. Every system receives only the user's service text and location "
           "text (`service_label`, `location_text`) and is scored against `workspace.golden_eval.judgments_dev` "
           "(29 queries, 28 with a recommendable facility, 1 'desert'). The test split was never read.\n",
           "## Summary\n",
           "- **Best system = the shipped defaults (`E9_shipped_defaults`)**: location resolver + v2 stage-1 candidates + "
           "minimum pool of 3 + multi-service intent + plausibility/source down-weights + 'evidence' solid gate + rules "
           "ranking (proof x closeness, no text model).\n",
           "- The large gains came from stage 1 and query understanding (location, candidates, pool size, intent), not "
           "from the reranker. Every text model (BM25, bi-encoder, 3 cross-encoders, NLI, Qwen2.5 0.5B as a yes/no "
           "verifier, ensemble) was tried on the same candidates; none gives a gain whose bootstrap interval excludes 0, "
           "and single cross-encoders lower P@3, so ranking stays rules-only (cheaper, deterministic, explainable).\n",
           "- Weight/distance/urgency tuning does not survive leave-one-query-out CV, so defaults were kept.\n\n",
           "## 1. Ablation: each step added on top of the previous one\n",
           table(main_tbl, ["experiment", "P@3", "nDCG@3", "P@3_j", "nDCG@3_j", "bad@3", "answered", "errors", "description"])]
    best = "E9_shipped_defaults" if "E9_shipped_defaults" in s.index else main_tbl.loc[main_tbl["nDCG@3"].idxmax(), "experiment"]
    ci_rows = []
    for base in ["E0_live_ce", "E0_live_rules", "E1_location_rules"]:
        if base in s.index:
            a = pq[(pq.experiment == base) & pq.answerable]; b = pq[(pq.experiment == best) & pq.answerable]
            for m in ["nDCG@3", "P@3"]:
                d, lo, hi = paired_bootstrap(a, b, m)
                ci_rows.append({"comparison": f"{best} vs {base}", "metric": m, "difference": d, "95% CI": f"[{lo:+.3f}, {hi:+.3f}]"})
    out += [f"\n**Shipped system: `{best}`** (the committed backend defaults). Paired bootstrap over queries (4,000 resamples):\n\n",
            table(pd.DataFrame(ci_rows), ["comparison", "metric", "difference", "95% CI"])]
    cv = RESULTS / "grid_cv_summary.csv"
    if cv.exists():
        c = pd.read_csv(cv)
        out += ["\n## 2. Stage-2 text models: same candidates, only the reranker changes\n",
                "For each text model all combinations of text weight (0.25, 0.4, 0.57, 0.8), travel-distance multiplier "
                "(0.5, 1, 2, 4), urgency factor (1, 0.6) and query style (keywords as live, or 'a hospital that provides X') "
                "were run. **LOO-CV**: for each query, the combination is picked on the other 27 queries and scored on the "
                "held-out one, so the number is not tuned on itself. 'in-sample best' is optimistic.\n\n",
                table(c.sort_values(["base", "LOO-CV nDCG@3"], ascending=[True, False]),
                      ["base", "text_model", "LOO-CV nDCG@3", "LOO-CV P@3", "LOO-CV P@3_j", "in-sample best nDCG@3", "most picked in CV"])]
    rg = RESULTS / "rules_grid_per_query.csv"
    if rg.exists():
        g = pd.read_csv(rg); a = g[g.answerable]
        piv = a.pivot_table(index="query_id", columns="config", values="nDCG@3")
        cvv = np.mean([piv.at[q, piv.drop(index=q).mean().idxmax()] for q in piv.index])
        out += ["\n## 3. Rules-only parameters (E6 base)\n",
                f"96 combinations of minimum pool size (2, 3, 5, 8), travel multiplier, single-statement weight and urgency. "
                f"In-sample best nDCG@3 {piv.mean().max():.3f}, **LOO-CV {cvv:.3f}**, i.e. no better than the defaults "
                f"(E6 {s.loc['E6_plausibility_rules', 'nDCG@3']:.3f}): tuning these on 28 queries mostly fits noise, so the "
                "defaults were kept (only the minimum pool of 3, tested separately in E5a, is used).\n\n"]
        for k in ["min_pool", "travel_mult", "tier3", "urgent"]:
            out.append(f"- mean nDCG@3 by `{k}`: " + ", ".join(f"{i}: {v:.3f}" for i, v in a.groupby(k)["nDCG@3"].mean().items()) + "\n")
    for title, col in [("service", "service"), ("query slice", "slice")]:
        sub = pq[pq.answerable & pq.experiment.isin(["E0_live_ce", "E0_live_rules", best])]
        t = sub.pivot_table(index=col, columns="experiment", values="P@3", aggfunc="mean").reset_index()
        out += [f"\n## P@3 by {title}\n", table(t, [col] + [c for c in ["E0_live_ce", "E0_live_rules", best] if c in t])]
    out += ["\n## How to read this\n",
            "- Labels are silver standard: produced by rules (`golden_eval.label_rules`), not by people. The recommender does "
            "not reuse those rules. Two v2 down-weights (a name announcing another specialty; inpatient-only services at a "
            "clinic) resemble checks in the label rules, so E6's small gain may be partly optimistic.\n",
            "- 28 answerable queries: differences below about 0.03 are within noise (see the bootstrap intervals).\n",
            "- `_j` metrics skip unjudged results; plain metrics count them as not relevant.\n",
            "- Reproduce: `python experiments/export_data.py`, `python pipeline/service_index_v2.py ...`, "
            "`python -m experiments.run_golden`, `python -m experiments.grid`, `python -m experiments.rules_grid`, "
            "`python -m experiments.report`.\n"]
    (ROOT / "RESULTS.md").write_text("".join(out))
    print((ROOT / "RESULTS.md").read_text()[:3000])


if __name__ == "__main__":
    main()
